package ru.home.dashboard;

/**
 * ═══════════════════════════════════════════════════════════════════════════
 *  ГЛАВНЫЙ ФАЙЛ НАСТРОЕК ПОД ВАШЕ УСТРОЙСТВО
 *
 *  Меняйте значения только здесь. После изменений пересоберите APK:
 *      build\build.ps1
 *
 *  Не знаете, что менять? Откройте PROMPT_RU.md, скопируйте промт в чат с
 *  нейросетью и укажите ссылку на репозиторий — она подберёт значения под
 *  ваш планшет.
 * ═══════════════════════════════════════════════════════════════════════════
 */
public final class DeviceConfig {

    private DeviceConfig() {
        // только константы
    }

    // ────────────────────────────── ГОРОД И ЧАСОВОЙ ПОЯС ─────────────────────

    /**
     * Часовой пояс панели в формате IANA (например, "Europe/Moscow",
     * "Asia/Yekaterinburg", "Europe/Berlin").
     * Пустая строка = системный часовой пояс планшета (обычный вариант).
     * Задавайте явно, если на устройстве сбит системный пояс.
     */
    public static final String TIME_ZONE = "";

    /**
     * true  — определять город автоматически по IP через wttr.in;
     * false — использовать координаты и название ниже.
     */
    public static final boolean AUTO_LOCATION = true;

    /** Координаты города (используются, если AUTO_LOCATION = false). */
    public static final double LATITUDE = 55.7558;
    public static final double LONGITUDE = 37.6173;

    /** Подпись города на панели (если AUTO_LOCATION = false). "" = без подписи. */
    public static final String CITY = "Москва";

    // ───────────────────────────── РАСПИСАНИЕ ЭКРАНА ────────────────────────

    /** Час, когда экран включается и панель переходит в дневной режим. */
    public static final int DAY_START_HOUR = 8;

    /** Час, когда экран гаснет и включается ночной режим. */
    public static final int DAY_END_HOUR = 21;

    /** Час, когда показывается вечерний список вещей. */
    public static final int PACKING_HOUR = 20;

    /** Не показывать список вещей в субботу (true — как в оригинале). */
    public static final boolean PACKING_SKIP_SATURDAY = true;

    /** Переводить планшет в беззвучный режим при запуске панели. */
    public static final boolean MUTE_SOUND = true;

    /** Яркость окна днём (0..1). */
    public static final float DAY_BRIGHTNESS = 0.62f;

    /** Яркость окна ночью (0..1), дополнительно рисуется затемнение. */
    public static final float NIGHT_BRIGHTNESS = 0.02f;

    // ──────────────────────────── ВЕЧЕРНИЙ СПИСОК ВЕЩЕЙ ──────────────────────

    /**
     * Стартовые пункты списка вещей. По умолчанию пусто: каждый добавляет
     * свои вещи сам кнопкой «+ Добавить свой пункт» (они сохраняются).
     *
     * Пример: { "Документы", "Ключи", "Зарядка" }
     */
    public static final String[] DEFAULT_PACKING_ITEMS = {};

    /**
     * Добавлять пункт «Тетрадь (предметы из календаря на завтра)».
     * Полезно школьникам и студентам; по умолчанию выключено.
     */
    public static final boolean NOTEBOOK_FROM_CALENDAR = false;

    // ───────────────────────────────── ВЁРСТКА ───────────────────────────────

    /**
     * Базовый размер макета в пикселях: панель нарисована под 600×1024
     * (портрет). Вёрстка масштабируется как min(ширина/600, высота/1024),
     * поэтому на планшетах с другим соотношением сторон она тоже помещается.
     * Менять нужно только вместе с правками координат в DashboardView.
     */
    public static final float DESIGN_WIDTH = 600f;
    public static final float DESIGN_HEIGHT = 1024f;
}
